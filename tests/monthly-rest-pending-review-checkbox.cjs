'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const src=fs.readFileSync('assets/port79-monthly-rest-dashboard.js','utf8');
const official=fs.readFileSync('assets/port79-monthly-rest-overtime.js','utf8');
new vm.Script(src,{filename:'port79-monthly-rest-dashboard.js'});
new vm.Script(official,{filename:'port79-monthly-rest-overtime.js'});
const context={window:{},document:{}};
vm.runInNewContext(src,context);
const ui=context.window.P79MonthlyRestDashboard;
const candidate={kind:'ready',id:'r1',date:'2026-11-21',name:'葉仲庭',category:'休',period:'休24-08',status:'可申報',disabled:false,checked:false};
const review={...candidate,id:'r2',name:'袁孟勤',status:'待核對',disabled:true};
const blocked={...candidate,id:'r3',status:'缺資料',disabled:false};
const old={kind:'existing',id:'REPORT_11',date:'2026-11-20',name:'袁孟勤',category:'休',period:'休24-08',status:'待核對',source:'考勤待確認'};
const completed={...old,status:'已核對出勤'};
const pendingPlan={kind:'plan',id:'p1',date:'2026-11-30',name:'王榮章',category:'休',period:'休08-16',status:'預排待核',disabled:false,checked:false};
const blockedPlan={...pendingPlan,id:'p2',disabled:true};
for(const row of [review,blocked,old,blockedPlan])
 assert.equal(ui.selectionMode(row),'review','pending audit items must be selectable for inspection');
assert.equal(ui.selectionMode(candidate),'native','verified candidate must use official checkbox');
assert.equal(ui.selectionMode(pendingPlan),'native','available plan must use official checkbox');
assert.equal(ui.selectionMode(completed),'none','already-verified existing records stay read-only');
const set=new Set();
const source=JSON.stringify({review,old,completed});
assert.equal(ui.reviewSelected(set,review),false);
assert.equal(ui.markForReview(set,review,true),true);
assert.equal(ui.markForReview(set,old,true),true);
assert.equal(ui.reviewSelected(set,review),true);
assert.equal(ui.reviewSelected(set,old),true);
assert.equal(set.size,2);
assert.equal(ui.markForReview(set,candidate,true),false,'cannot bypass official candidate checkbox');
assert.equal(ui.markForReview(set,completed,true),false,'cannot mark a completed filing for re-report');
assert.equal(ui.markForReview(set,old,false),true);
assert.equal(ui.reviewSelected(set,old),false);
assert.equal(JSON.stringify({review,old,completed}),source,'local audit selection must not mutate any source or cloud report');
assert.notEqual(ui.selectionKey(old),ui.selectionKey({...old,id:'REPORT_12'}),'separate report ids must not collide');
assert.notEqual(ui.selectionKey(old),ui.selectionKey({...old,date:'2026-11-21'}),'separate dates must not collide');
assert.match(src,/selectable=state.tab==='pending'&&selectionMode\(r\)!=='none'/);
assert.match(src,/updatePick\(row,target.checked\)/);
assert.match(src,/state.reviewSelected/);
assert.match(src,/q\('#mrUxReviewSummary'\)\.innerHTML/);
assert.match(src,/q\('#mrUxAll'\)\.onchange/);
assert.match(src,/!submit\.disabled&&\/申報\//,'official submission still checks native button');
assert.match(src,/if\(!submit\|\|!sourceRows\(el\)\.ready\.some/,'audit-only selection cannot submit');
assert.match(official,/if\(!fullDayEvidence\(fresh,r.empId,r.date,attendance\[0\]\)\)/,'formal eight-hour guard unchanged');
assert.match(official,/if\(meta.overtimeReport\|\|meta.overtime\|\|meta.forEmpId/,'duplicate report protection unchanged');
console.log('PASS pending review checkboxes: read-only audit rows can be selected locally, select-all and batch review wired; official filing permissions stay unchanged');
