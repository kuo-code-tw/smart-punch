const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync('work-hours/index.html','utf8');
const open='<style id="p79-overtime-table-compact-attendance-20261022">';
const from=html.indexOf(open),to=html.indexOf('</style>',from);
assert(from>=0&&to>from,'overtime detail must retain a scoped font rule');
const css=html.slice(from,to);
const rule=(selector)=>{const pos=css.indexOf(selector+'{');assert(pos>=0,'missing selector: '+selector);return css.slice(pos,css.indexOf('}',pos)+1)};
const table='body.p79-work-hours-page #adminContentOvertime #p79OvertimeStatsTable';
const body='body.p79-work-hours-page #adminContentOvertime #overtimeTableBody';
const main=rule(table),head=rule(table+' thead th'),row=rule(body+'>tr'),cell=rule(body+' td'),name=rule(body+' td[data-label="姓名"]'),inline=rule(body+' .p79-overtime-inline'),detail=rule(body+' .p79-overtime-inline>span');
assert(main.includes('font-size:14px!important'),'main table text should be a comfortable 14px');
assert(head.includes('font-size:13px!important'),'header text should be compact and readable');
assert(cell.includes('font-size:14px!important'),'dates, departments, clock-in/out and hours should use 14px');
assert(name.includes('font-size:15px!important'),'employee names should stand out without dominating the row');
assert(detail.includes('font-size:13px!important'),'overtime status should fit more comfortably');
assert(row.includes('height:auto!important')&&row.includes('min-height:60px!important'),'rows should be compact yet expand for wrapped text');
assert(inline.includes('flex-wrap:wrap!important')&&inline.includes('overflow:visible!important'),'long overtime descriptions must remain visible');
assert(detail.includes('white-space:normal!important'),'overtime text must wrap rather than disappear');
assert(inline.includes('min-width:0!important'),'status area may shrink without clipping rightmost column');
assert(css.includes('@media(max-width:900px)'),'narrow displays must retain responsive handling');
const before=html.slice(0,from),after=html.slice(to);
assert(!after.includes('body.p79-work-hours-page #adminContentOvertime #overtimeTableBody td{font-size:13px!important'),'obsolete 13px override must not return later');
console.log('PASS balanced 14px overtime detail, 15px names, 13px status, compact expanding rows and wrapping');
