// Prior-month leave overtime: original date/month quota, current processing month note, and 83-person review.
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync('assets/port79-monthly-rest-overtime.js','utf8');
const month='2026-09',processMonth='2026-10',date='2026-09-05',reportedDate='2026-09-06';
let today='2026-10-27',uid=0;
const c={window:null,console,crypto:{randomUUID:()=> 'TEST-'+(++uid)},Date,Intl:{DateTimeFormat:function(){return{format:()=>today}}}};
c.window=c;vm.createContext(c);
vm.runInContext(fs.readFileSync('assets/port79-rest-allocation.js','utf8'),c);
c.p79MonthlyRestContext={employmentStart:()=>''};
c.P79RestAttendance={state:()=> 'worked',isLeaveDay:()=>false};
c.P79Overtime={inferRule:(start,end,_date,opts)=>opts[0]||null};
c.P79OvertimeReason={classify:()=>({exempt:true,kind:'cover'})};
vm.runInContext(src,c);
const api=c.P79MonthlyRest,people=Array.from({length:83},(_,i)=>({name:i===0?'胡毓麒':'員工'+i,empId:'E'+i}));
const days=c.p79RestQuota(month).days,dates=Array.from({length:days},(_,i)=>month+'-'+String(i+1).padStart(2,'0'));
const rows=people.map(emp=>{
 const roster={...Object.fromEntries(dates.map(d=>[d,'早'])),__meta:{}};
 roster[date]='休';roster[reportedDate]='休';
 roster.__meta[reportedDate]={restCategory:'休',overtimeOriginalShift:'休',overtimeReport:{id:'R-'+emp.empId,category:'休',code:'休08-16'}};
 return {empId:emp.empId,schedule:roster};
});
const pairs=people.map(emp=>({empId:emp.empId,date,start:date+'T08:00',end:date+'T16:00'}));
const snapshot={schedules:rows,pairs,leaveDates:[],leaveCoverAssignments:people.map(emp=>({startDate:reportedDate,endDate:reportedDate,leaveEmpId:'ANOTHER',workerIds:[emp.empId]}))};
const before=JSON.stringify(snapshot),rules=['國','休','例'].map(cat=>[cat,cat+'08-16',8,8,'','','08','16']);
assert.equal(api.previousMonth?.('2026-01'),'2025-12','December rollover') ;
assert.equal(api.backfillContext?.(month,'2026-10-27').historical,true);
assert.equal(api.backfillContext?.(month,'2026-10-27').sourceMonth,month);
assert.equal(api.backfillContext?.(month,'2026-10-27').handlingMonth,processMonth);
assert.match(api.backfillContext?.(month,'2026-10-27').note,/跨月補報.*2026-10.*2026-09/);
assert.equal(api.workflowStage(month,'2026-10-27').key,'closing');
assert.equal(api.backfillContext?.('2026-10','2026-10-27').historical,false);
const first=api.balance(people[0],rows[0].schedule,month,snapshot);
assert.equal(first.reported.休,1,'One saved rest-day overtime with substitution metadata must still consume 休');
assert.equal(first.ledger.some(x=>x.date===reportedDate&&x.kind==='reported'),true);
assert.equal(first.ledger.some(x=>x.date===reportedDate&&x.kind==='exemptOvertime'),false,'Own rest report is not treated as exempt');
assert.equal(first.ledger.some(x=>x.date===date&&x.kind==='workedRestUnreported'),true,'Actual punched 休 day must not be called taken leave');
assert.equal(first.ledger.some(x=>x.date===date&&x.kind==='off'),false);
assert.equal(first.off.休+first.reported.休+first.reserved.休+first.remaining.休,first.quota.休,'Rest quota is conserved');
const plan=api.plan(snapshot,people,month,rules),summary=api.workflowAudit(plan);
assert.equal(plan.balances.length,83,'All active in-scope workers must be individually audited');
assert.equal(summary.checked,83);
assert.equal(summary.people.length,83,'All employees appear in the audit, not just staff with quota shortage');
assert(summary.people.some(s=>s.includes('胡毓麒')&&s.includes('正式加班 例0／休1')),'Employee existing 休 report shown in ledger');
assert(plan.rows.some(r=>r.date===date&&r.category==='休'&&r.planned===false),'An unreported actual rest-day shift before the 15th is a historical 休 suggestion');
assert(!plan.rows.some(r=>r.date===date&&r.category!=='休'),'A 休 day must not be used as 例 or 國 make-up');
assert(plan.rows.every(r=>r.date.startsWith(month)),'Original overtime date always belongs to September');
assert.equal(JSON.stringify(snapshot),before,'Audit leaves all rosters, attendance and official reports untouched');
assert(src.includes('q(\x27#mrPrior\x27).onclick'),'One-click last-month backfill button must be wired');
assert(src.includes("note:backfillContext(loadedMonth).note"),'Original/handling months must be stored in the report note');
assert(src.includes("a.snapshot(loadedMonth,false,false,true)"),'Read and reconcile original work month');
assert(src.includes("const fresh=await a.snapshot(loadedMonth,false,false,true)"),'Immediately before save, re-fetch original month');
assert(src.includes("if(meta.overtimeReport||meta.overtime||meta.forEmpId||meta.coverAssignmentId"),'Do not duplicate already saved reports');
assert(src.includes("attendance.length!==1"),'Requires exactly one complete attendance evidence pair');
assert(src.includes("context.historical&&!confirm"),'Historical backfill needs explicit operator confirmation');
assert(src.includes("r.date.startsWith(loadedMonth+'-')"),'Cannot move original date into processing month');
console.log(JSON.stringify({passed:25,failed:0,reviewed:summary.checked,scope:'September overtime credited to September while processed October; rest-day existing/formal reports; 83-person non-mutating review'}));
