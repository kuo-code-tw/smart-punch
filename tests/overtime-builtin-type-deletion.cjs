'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('assets/port79-overtime-report.js','utf8');
const win={};
vm.runInNewContext(source,{window:win,Date,Intl,Set,Map,TextEncoder});
const api=win.P79Overtime;
const original=api.defaults(),snapshot=JSON.stringify(original);
const CONFIG=api.DELETED_CONFIG;
const deleted={[CONFIG]:['平日延長加班']};
const selected=api.typeOptions(deleted,original).map(x=>x.name);
assert(!selected.includes('平日延長加班'),'deleted builtin must not return to new report type list');
assert(selected.includes('休息日加班'),'other builtin type must stay');
const active=api.activeReportRows(original,deleted);
assert(!active.some(row=>row[0]==='延'),'deleted extension periods hidden from active list');
assert(active.some(row=>row[0]==='休'),'other periods intact');
const support=api.activeSupportPeriods(active,deleted);
assert.equal(support.added,0,'auto-adding extension support must not resurrect deleted builtin');
assert(!support.rows.some(row=>row[0]==='延'));
const archived=original.filter(row=>row[0]==='延');
const keepHistory=api.validate([...active,...archived]);
assert.equal(keepHistory.length,original.length,'old conversion rules remain restorable for history');
assert.equal(JSON.stringify(original),snapshot,'deletion never mutates the historical source rows');
const restored=api.typeOptions({[CONFIG]:[]},original).map(x=>x.name);
assert(restored.includes('平日延長加班'),'administrator can restore a builtin');
assert(api.activeReportRows(original,{[CONFIG]:[]}).some(row=>row[0]==='延'));
assert(source.includes('p79OtBuiltinDelete'),'delete/restore controls must be rendered in manager');
assert(source.includes('const archived=fresh.rows.filter(row=>removedBuiltinNames.has(ruleType(row)))'),'historic rules remain in cloud for old report validation');
assert(source.includes('loadedDeleted=JSON.stringify([...deletedBuiltins(check.config)])'),'cloud readback verifies deletion tombstone');
assert(source.includes('const latestRules=await loadRules()'),'new reports must load latest cloud types');
assert(source.includes('所選加班類型或時段已從雲端刪除'),'stale tabs must block old deleted types');
new vm.Script(source);
console.log('PASS builtin delete/restore, auto-resurrection prevention, historical rule preservation, cloud verification and stale form guard');
