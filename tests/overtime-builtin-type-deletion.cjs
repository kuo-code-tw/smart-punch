'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('assets/port79-overtime-report.js','utf8'),win={};
vm.runInNewContext(source,{window:win,Date,Intl,Set,Map,TextEncoder});
const api=win.P79Overtime,rows=api.defaults(),snapshot=JSON.stringify(rows);
assert.equal(api.typeOptions({},rows).length,0,'no categories are preinstalled');
assert.equal(api.activeReportRows(rows,{}).length,0,'legacy periods are not new filing options');
const selected={overtimeReportTypesV1:[['休息日加班','休'],['自訂延時','延']]};
assert.deepEqual([...api.typeOptions(selected,rows).map(x=>x.name)],['休息日加班','自訂延時']);
assert.equal(api.activeReportRows(rows,selected).filter(r=>r[0]==='休').length>0,true);
const archivedKey='builtin:休息日加班|休08-16';
const archived={...selected,overtimeArchivedRuleKeysV1:[archivedKey]};
assert(!api.activeReportRows(rows,archived).some(r=>r[1]==='休08-16'));
assert.equal(api.typeOptions({overtimeReportTypesV1:[['自訂延時','延']]},rows).some(t=>t.name==='休息日加班'),false);
assert.equal(JSON.stringify(rows),snapshot,'historic conversion rows are not mutated by menu changes');
assert.equal(api.specialRows([],{}).length,0,'unconfigured special types are never auto-added');
assert(!source.includes('p79OtBuiltinDelete'),'no built-in deletion / restore buttons');
assert(!source.includes('renderBuiltinTypeList'),'no auto-created built-in list');
assert(source.includes('const archiveKeys=[...new Set(archived.map(ruleKey))]'),'deleted type rules archived in cloud');
assert(source.includes('loadedArchived=JSON.stringify(check.config[ARCHIVED_CONFIG]||[])'),'readback verifies archived cloud rules');
assert(source.includes('所選加班類型或時段已從雲端刪除'),'old browser cannot resubmit a deleted type');
new vm.Script(source);
console.log('PASS manual overtime types, permanent deletion without restore, historical rules archived');
