const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('work-hours/index.html','utf8');
const start=html.indexOf('<details id="p79OvertimeJobTitleSummary"'),end=html.indexOf('</details>',start);
assert(start>0&&end>start,'job-title overtime table must exist');
const section=html.slice(start,end);
const headers=[...section.matchAll(/<th\b[^>]*>(.*?)<\/th>/g)].map(m=>m[1]);
assert.deepEqual(headers,['職稱','總人數','請假天數','未換算加班（小時）','每人平均']);
assert(!section.includes('已申報人數')&&!section.includes('有效筆數'),'unwanted count columns are not visible');
const render=html.slice(html.indexOf('const jobBody=document.getElementById(\'p79OvertimeJobTitleRows\')'),html.indexOf('const deptNotice=document.getElementById(\'p79OvertimeJobTitleNotice\')'));
assert(render.includes("g.raw+'</td>'"),'raw declared overtime must remain the source of displayed hours');
assert(render.includes("formatAverage(g.rawAverage)"),'per-person average uses unconverted hours divided by all staff');
assert(!render.includes("g.people+'</td>'")&&!render.includes("g.count+'</td>'"),'reporter/record counts cannot remain as hidden extra cells');
assert(render.includes('colspan="5"'),'empty result must span exactly five columns');
assert(render.includes('p79-job-total'),'totals should be visually distinct');
const css=html.slice(html.indexOf('<style id="p79-job-title-summary-color-v20261026">'),html.indexOf('</style>',html.indexOf('<style id="p79-job-title-summary-color-v20261026">')));
for(const cls of ['p79-job-role','p79-job-staff','p79-job-leave','p79-job-hours','p79-job-average','p79-job-total'])assert(css.includes(cls),'missing table color accent '+cls);
assert(css.includes('html[data-theme="dark"]'),'dark-mode contrast must remain defined');
const a=html.indexOf('        function p79BuildOvertimeJobTitleSummary(rows,personnel=[]) {'),b=html.indexOf('        // 所有職稱人員的已核准請假天數',a);
assert(a>0&&b>a);
const ctx={Map,Set,Number,String,Array,Math};vm.createContext(ctx);vm.runInContext(html.slice(a,b),ctx);
const staff=[{empId:'A',jobTitle:'F/L'},{empId:'B',jobTitle:'F/L'},{empId:'C',jobTitle:'ARMG'}];
const report={empId:'A',jobTitle:'F/L',dateKey:'2026-10-20',reportVerified:true,overtimeReport:{id:'R1',declaredHours:8,convertedHours:12.7}};
const result=ctx.p79BuildOvertimeJobTitleSummary([report],staff),role=result.groups.find(g=>g.jobTitle==='F/L');
assert.equal(role.raw,8);
assert.equal(role.rawAverage,4,'averages must include non-overtime staff and must not use converted hours');
assert.equal(result.totals.raw,8);
assert.equal(result.totals.rawAverage,8/3);
console.log('PASS five-column colored job-title overtime summary, raw hours, average denominator, totals and dark palette');
