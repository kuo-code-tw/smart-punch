'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'assets/port79-reference-dashboard.js'),'utf8');
const css=fs.readFileSync(path.join(root,'assets/port79-reference-dashboard.css'),'utf8');
const title=html.indexOf('最新匯入船舶');
const head=html.slice(title,title+420);
assert(title>=0,'latest imported vessel panel exists');
assert(head.includes('<th>船名（中文）</th>'),'ship header identifies bilingual name');
assert(!head.includes('<th>狀態</th>'),'status column removed');
assert(head.includes('colspan="6"'),'empty table has six columns');
const begin=js.indexOf('if(table)table.innerHTML=latest.length?');
const end=js.indexOf("const ym=$('p79DashMonth')",begin);
assert(begin>=0&&end>begin,'imported ship renderer exists');
const rank=js.slice(begin,end);
assert(rank.includes('p79r-vessel-one-line')&&rank.includes('p79r-vessel-chinese-name'),'English/Chinese one-line markup');
assert(rank.includes('esc(chinese)'),'the verified Chinese name is displayed');
assert(!rank.includes('p79r-state'),'status cell is not rendered');
assert(rank.includes('colspan="6"'),'no-vessels row spans six columns');
assert(css.includes('#p79DashShipRanking td:nth-child(2)'),'bilingual cells have scoped styles');
assert(css.includes('white-space:nowrap'),'ship names do not wrap');
console.log('PASS: one-line bilingual imported vessel rows without status column');
