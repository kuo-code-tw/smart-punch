'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../aqc-efficiency/index.html'),'utf8');
const ui=fs.readFileSync(path.join(__dirname,'../assets/port79-aqc-multi-rod.js'),'utf8');
const found=html.match(/<style id="p79-aqc-multi-rod-table-compact-20261028">([\s\S]*?)<\/style>/);
assert.ok(found,'compact style block exists in the published efficiency entrypoint');
const css=found[1];
assert.match(css,/#view-multi-rod \.tbl th\{font-size:13px!important;/);
assert.match(css,/#view-multi-rod \.tbl td\{font-size:14px!important;/);
assert.ok(css.includes('#view-multi-rod #multiRodBody td:nth-child(1)'),'date column compact');
assert.ok(css.includes('#view-multi-rod #multiRodBody td:nth-child(5)'),'audit column compact');
assert.ok(css.includes('#view-multi-rod #multiRodBody td:nth-child(5) summary{font-size:13px!important}'),'review link stays readable');
assert.match(css,/padding:8px 10px!important/,'rows more compact without removing vertical space');
assert.match(css,/#view-multi-rod #multiRodSourceAudit/,'source audit compact as shown in screenshot');
assert.match(css,/#view-multi-rod \.tbl td\{text-align:center!important;vertical-align:middle!important\}/,'all table data aligned center');
assert.ok(css.includes('#view-multi-rod .tbl th,'),'table headings aligned center');
assert.ok(css.includes('#view-multi-rod #multiRodBody td:nth-child(3)>div{text-align:center!important}'),'ship rows override prior text-left');
assert.ok(css.includes('#view-multi-rod #multiRodBody td:nth-child(5) details{margin-inline:auto!important;text-align:center!important}'),'details centered as block');
assert.ok(css.includes('#view-multi-rod #multiRodBody td:nth-child(5) details summary{text-align:center!important}'),'review link centered');
assert.ok(css.includes('#view-multi-rod #multiRodBody td:nth-child(5) details div{text-align:center!important}'),'expanded evidence centered');
assert.match(ui,/class="text-left py-0\.5"/,'test acknowledges original ship text-left override');
assert.match(ui,/class="text-left max-w-\[380px\]"/,'test acknowledges original details text-left override');
const cssRules=css.split('\n').filter(x=>x.trim()&&!x.trim().startsWith('/*'));
assert.ok(cssRules.every(line=>line.includes('#view-multi-rod')||line.startsWith('#view-multi-rod')||line.startsWith('}')),'no unscoped selectors affecting other pages');
assert.match(ui,/const ID='view-multi-rod'/,'selector matches real section ID');
assert.match(ui,/id="multiRodBody"/,'target remains the intended data table');
assert.match(html,/port79-aqc-concurrent\.js/);
assert.match(html,/port79-aqc-multi-rod\.js/);
console.log('PASS AQC multi-rod compact centered typography: scoped table, centered ship/link/evidence');
