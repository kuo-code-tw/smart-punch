'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('work-hours/index.html','utf8');
const start=html.indexOf('<div id="adminContentOvertime"');
const end=html.indexOf('<div id="adminContent',start+10);
assert(start>=0&&end>start,'Overtime overview exists');
const overview=html.slice(start,end);
assert(overview.includes('class="p79-ot-btn-report"'),'restore top-level +申報加班 action');
assert(overview.includes('>加班明細</button>')&&overview.includes('>申報加班</th>'),'restore original overtime report table heading');
const action=html.indexOf('<div class="p79-overtime-row-actions">');
assert(action>=0,'row controls exist');
const deleteStart=html.indexOf('${p79CanDeleteOvertime()',action);
assert(deleteStart>action,'row delete controls remain');
const leading=html.slice(action,deleteStart);
assert(leading.includes('>申報加班</button>'),'unreported rows may submit a new report');
assert(leading.includes('p79ReportWorkOvertimeRow(${rowIndex})'),'pending row report button routes to original handler');
assert(leading.includes('row.reportVerified')&&leading.includes('>修改申報</button>'),'existing formal records keep correction action');
assert(html.slice(deleteStart,deleteStart+1800).includes('>刪除加班</button>'),'delete button retained');
assert(html.includes('id="overtimePendingEstimateHours"'),'punch-derived overtime counter retained');
assert(html.includes('p79UnreportedOvertimeSummary(rows)'),'current-scope pending overtime computation retained');
assert(html.includes('>申報加班</th>'),'table restored to original header');
assert(html.includes('onclick="p79OpenAdminAttendanceOvertime(${rowIndex})"'),'separate attendance admin report action remains available');
console.log('PASS restored overtime reporting controls: top-level report, per-row report, formal edit, delete and statistics');
