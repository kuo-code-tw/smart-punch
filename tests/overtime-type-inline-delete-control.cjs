'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('assets/port79-overtime-report.js','utf8');
const g={};vm.runInNewContext(source,{window:g,Date,Intl,Set,Map,TextEncoder});
const api=g.P79Overtime;
assert(api);
assert(source.includes('id="p79NewTypeName"'));
assert(source.includes('id="p79AddType"'));
assert(source.includes('id="p79OvertimeTypeList"'));
assert(source.includes('id="p79AddedTypeList"'));
assert(source.includes("button.className='p79OtDeleteType'"),'one delete button per type');
assert(!source.includes('p79ManageTypeSelect'),'no redundant delete dropdown');
assert(!source.includes('p79BuiltinTypeList'),'no preinstalled list');
assert(!source.includes('p79OtBuiltinDelete'),'no restore button');
assert(source.includes('尚未新增加班類型'),'empty list is rendered');
assert.equal((source.match(/p79OtSave'\)\.click\(\)/g)||[]).length,2,'add and delete directly persist');
assert(source.includes("global.confirm('確定刪除加班類型"),'delete is confirmed');
assert(source.includes('[ARCHIVED_CONFIG]:archiveKeys'),'history is retained without a restore action');
assert.equal(api.typeOptions({},api.defaults()).length,0,'no automatic type list');
assert(source.includes('class="p79-ot-type-manager"'),'compact two-column manager renders');
assert(source.includes('id="p79OvertimeTypeList"'),'type list remains available');
assert(source.includes('<details id="p79RoleTypeDefaultsPanel"'),'job title mapping collapses by default');
assert(source.includes('p79-ot-table-help'),'period table gets compact heading');
assert(source.includes('#p79OvertimeOptionsDialog .p79-ot-table-wrap{flex:1 1 200px!important'),'rule table owns remaining dialog height');
assert(source.includes('#p79OvertimeOptionsDialog #p79OvertimeTypeList{max-height:72px'),'type list has bounded height');
assert(source.includes('id="p79OtSave"'),'original save action retained');
assert(source.includes('id="p79OtAdd"'),'period add action retained');
assert(source.includes('尚未新增任何加班類型'),'empty type select must explain missing setup');
assert(source.includes('請先新增加班類型及出勤時段'),'empty period select must show setup instructions');
assert(source.includes('請先在上方新增至少一種加班類型'),'period editor must not open with no type');
assert(source.includes('請按「＋新增出勤時段」完成設定'),'saved type without periods must prompt period setup');
assert(source.includes('＋新增／管理加班類型與時段'),'filing form must link to type manager');
assert(source.includes('雲端尚未新增加班類型；請按「＋新增／管理加班類型與時段」'),'cloud reload must not falsely claim available options');
new vm.Script(source);
console.log('PASS single list, inline permanent delete, immediate cloud sync and no preinstalled types');
