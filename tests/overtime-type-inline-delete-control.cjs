'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('assets/port79-overtime-report.js','utf8');
const g={};vm.runInNewContext(source,{window:g,Date,Intl,Set,Map,TextEncoder});
const api=g.P79Overtime;
assert(api,'module remains available');
assert(source.includes('id="p79NewTypeName"'),'new type input retained');
assert(source.includes('id="p79AddType"'),'new type add action retained');
assert(source.includes('id="p79ManageTypeSelect"'),'inline deletion dropdown added in new type section');
assert(source.includes('id="p79ManageTypeAction"'),'inline deletion button added in new type section');
assert(source.indexOf('id="p79AddType"')<source.indexOf('id="p79ManageTypeSelect"'),'delete control placed directly after new type control');
assert(source.includes("manageTypeButton.onclick=()=>"),'delete action is wired');
assert(source.includes("target.click(); // Existing confirmation and safe-delete/restore logic."),'existing confirmation handler reused');
assert(source.includes("manageTypeButton.textContent=selected?.removed?'恢復加班類型':'刪除加班類型'"),'restore is available for deleted builtin');
assert(source.includes("manageTypeButton.disabled=!editable||!selected"),'disabled until cloud and permission confirmation');
assert(source.includes("renderAddedTypeList();refreshManageTypePicker();"),'custom delete refreshes inline dropdown');
assert(source.includes("renderBuiltinTypeList();refreshManageTypePicker();"),'builtin delete refreshes inline dropdown');
assert(source.includes("const archived=fresh.rows.filter(row=>removedBuiltinNames.has(ruleType(row)))"),'historical conversion rows retained');
const rows=api.defaults();
const types=api.typeOptions({overtimeReportTypesV1:[['平日延時加班','延']]},rows);
assert.equal(types.filter(x=>x.name==='平日延時加班').length,1);
assert.equal(types.filter(x=>x.name==='平日延長加班').length,0);
new vm.Script(source);
console.log('PASS inline delete/restore selector in add-type section, permissions and cloud safety, historic conversions, no duplicate extension type');
