'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('assets/port79-overtime-report.js','utf8'),g={};
vm.runInNewContext(source,{window:g,Date,Intl,Set,Map,TextEncoder});
const api=g.P79Overtime;
assert(api);
for(const id of ['p79NewTypeName','p79AddType','p79OvertimeTypeList','p79AddedTypeList','p79OtSave','p79OtAdd'])
 assert(source.includes('id="'+id+'"'),id+' must remain');
assert(source.includes("button.className='p79OtDeleteType'"),'delete each configured type');
assert(source.includes("button.textContent='×'"),'compact accessible delete affordance in chip');
assert(source.includes('data-ot-category'),'category color preserved');
assert(source.includes("global.confirm('確定刪除加班類型"),'type deletion requires confirmation');
assert(source.includes("global.confirm('確定刪除加班時段"),'period deletion requires confirmation');
assert.equal((source.match(/p79OtSave'\)\.click\(\)/g)||[]).length,0,'stage additions/deletions for explicit final save');
assert(source.includes("refreshRuleCount()"),'list counts refresh after changes');
assert(source.includes('[ARCHIVED_CONFIG]:archiveKeys'),'historic report rules retained in cloud');
assert(source.includes('[HIDDEN_MANAGER_RULES]:hiddenManagerKeys'),'deleted periods stay hidden');
assert.equal(api.typeOptions({},api.defaults()).length,0,'no automatic installed types');
assert(source.includes('p79-ot-type-manager'),'existing and new type controls remain');
assert(source.includes('新增加班類型'),'creation panel matches user design');
assert(source.includes('請先在上方新增至少一種加班類型'),'cannot create period without configured type');
assert(source.includes('＋新增／管理加班類型與時段'),'filing form links to manager');
assert(!source.includes('p79OtBuiltinDelete'),'never add built-in delete-restore UI');
new vm.Script(source);
console.log('PASS inline type and period deletion with explicit save, readable colored category chips and cloud safeguards');
