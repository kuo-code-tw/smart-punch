'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const engine=require('../attendance/v6-engine.js');
globalThis.P79AttendanceV6=engine;
const alert=require('../assets/port79-home-early-punch-alert.js');
const now=clock=>Date.parse('2026-11-10T'+clock+'+08:00');
const punch=(emp,status,clock)=>({id:emp+'-'+status+'-'+clock,empId:emp,attNo:emp==='E1'?'001':'002',
 name:emp==='E1'?'早班測試甲':'早班測試乙',status,timeStr:'2026/11/10 '+clock});
const in1=punch('E1','上班簽到','08:00:00'),out1=punch('E1','下班簽退','16:03:00');
const in2=punch('E2','上班簽到','08:00:00'),out2=punch('E2','下班簽退','16:00:00');
const worker1=()=>({empId:'E1',attNo:'001',name:'早班測試甲',group:'A組',schedule:{'2026-11-10':'早'}});
const worker2=()=>({empId:'E2',attNo:'002',name:'早班測試乙',schedule:{'2026-11-10':'早'}});
const verify=(records,clock,people=[worker1(),worker2()])=>alert.analyze({records},{schedules:people},'2026-11',{now:now(clock)});
let report=verify([in2,out2],'08:29:59');assert.equal(report.count,0,'no alert before start grace');
report=verify([in2,out2],'08:31:00');assert.equal(report.count,1,'missing clock-in appears after 08:30');
assert.equal(report.details[0].reason,'缺少上班卡');
assert.equal(report.details[0].name,'早班測試甲');
assert.equal(report.details[0].shift,'早');
report=verify([in2,out2],'17:01:00');assert.equal(report.count,1,'both punches absent after end grace');
assert.equal(report.details[0].reason,'上下班皆無卡');
report=verify([in1,in2,out2],'16:59:59');assert.equal(report.count,0,'never flag a checkout before 17:00');
report=verify([in1,in2,out2],'17:01:00');assert.equal(report.count,1);
assert.equal(report.details[0].reason,'缺少下班卡');
assert.match(report.details[0].clockIn,/08:00:00/);
report=verify([out1,in2,out2],'17:01:00');assert.equal(report.count,1);
assert.equal(report.details[0].reason,'缺少上班卡');
report=verify([in1,out1,in2,out2],'17:01:00');assert.equal(report.count,0,'complete shift is clear');
report=verify([],'17:01:00',[worker1()]);assert.equal(report.count,0,'empty cloud feed does not accuse everyone');
assert.equal(report.unknownDays,1,'no day coverage stays uncertain');
report=verify([in2,out2],'17:01:00',[{...worker1(),schedule:{'2026-11-10':'休'}},worker2()]);
assert.equal(report.count,0,'rest day is not early duty');
report=verify([in2,out2],'17:01:00',[{...worker1(),schedule:{'2026-11-10':'早',__meta:{'2026-11-10':{approvedLeave:true}}}},worker2()]);
assert.equal(report.count,0,'approved leave suppresses false warnings');
const extended={...worker1(),schedule:{'2026-11-10':'早',__meta:{'2026-11-10':{overtime:true,overtimeEnd:'20:00'}}}};
report=verify([in1,in2,out2],'17:01:00',[extended,worker2()]);
assert.equal(report.count,0,'approved overtime extends checkout window');
report=verify([in1,in2,out2],'21:01:00',[extended,worker2()]);
assert.equal(report.count,1,'extension is reviewed after 60-min grace');
const duplicateRoster=[worker1(),{...worker1()},worker2()];
report=verify([in2,out2],'17:01:00',duplicateRoster);
assert.equal(report.count,1,'same roster person/date deduped');
report=verify([in1,out1,in2,out2],'17:01:00',[worker1(),worker2()]);
assert.equal(report.count,0);
report=alert.analyze({records:[]},null,'2026-11',{now:now('17:01:00')});
assert.equal(report.count,null,'unloaded roster is not a misleading zero');
const emptyData={records:[in2,out2]},rosterData={schedules:[worker1(),worker2()]};
const before=JSON.stringify([emptyData,rosterData]);
alert.analyze(emptyData,rosterData,'2026-11',{now:now('17:01:00')});
assert.equal(JSON.stringify([emptyData,rosterData]),before,'audit never mutates source');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'../assets/port79-monthly-dashboard.css'),'utf8');
const js=fs.readFileSync(path.join(__dirname,'../assets/port79-monthly-dashboard.js'),'utf8');
assert(html.includes('id="p79DashEarlyPunchTrigger"'));
assert(html.includes('id="p79DashEarlyPunchCount"'));
assert(html.includes('id="p79DashEarlyPunchDialog"'));
assert(html.includes('assets/port79-home-early-punch-alert.js?v=20261110-morning-review-v1'));
assert(html.includes('port79-monthly-dashboard.js?v=20261108-lashing-completion-v1'), 'existing dashboard version test remains compatible');
assert(css.includes('grid-template-columns:repeat(5,minmax(0,1fr))'));
assert(css.includes('grid-template-columns:repeat(2,minmax(0,1fr))'));
assert(js.includes('root.P79HomeEarlyPunchAlert?.render('),'homepage renders from its official data');
assert(js.includes('root.P79HomeEarlyPunchAlert?.bind(async()=>'),'card opens fresh official comparison');
new vm.Script(fs.readFileSync(path.join(__dirname,'../assets/port79-home-early-punch-alert.js'),'utf8'));
new vm.Script(js);
delete globalThis.P79AttendanceV6;
console.log('PASS 早班漏卡警示：08:30 上班、17:00 下班、加班延長、休假排除、空資料保護、重複排班、五格響應版面及唯讀核對');
