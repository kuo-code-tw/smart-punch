assert(cards.includes('class="p79d-kpi p79d-early-alert"'),'fourth card is ONE standalone early-punch alert');
assert(!block.includes('p79d-kpi-combined')&&!block.includes('p79d-kpi-subcard'),'no cramped nested KPI card');
